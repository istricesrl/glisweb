CREATE OR REPLACE PROCEDURE `__patch_residui_ordine__`()
BEGIN

    DECLARE fine INT DEFAULT 0;
    DECLARE errore INT DEFAULT 0;
    DECLARE messaggio TEXT DEFAULT NULL;
    DECLARE v_tabella CHAR(64) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_canone, v_deploy, v_clausole MEDIUMTEXT CHARACTER SET utf8 COLLATE utf8_general_ci;

    DECLARE lista CURSOR FOR
        SELECT DISTINCT o.`tabella`
        FROM `__patch_residui_ordine__` AS o
        INNER JOIN information_schema.TABLES AS t
            ON t.TABLE_SCHEMA = database() AND t.TABLE_NAME = o.`tabella` AND t.TABLE_TYPE = 'BASE TABLE'
        ORDER BY o.`tabella`;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET fine = 1;

    SET SESSION group_concat_max_len = 1048576;
    SET @residui_controlli = @@foreign_key_checks;
    SET @residui_ordine_tabelle = 0;
    SET @residui_ordine_note = NULL;

    OPEN lista;

    ciclo: LOOP

        FETCH lista INTO v_tabella;
        IF fine = 1 THEN
            LEAVE ciclo;
        END IF;

        SELECT group_concat( o.`colonna` ORDER BY o.`posizione` SEPARATOR ',' ) INTO v_canone
            FROM `__patch_residui_ordine__` AS o
            INNER JOIN information_schema.COLUMNS AS c
                ON c.TABLE_SCHEMA = database() AND c.TABLE_NAME = o.`tabella` AND c.COLUMN_NAME = o.`colonna`
            WHERE o.`tabella` = v_tabella;

        SELECT group_concat( c.COLUMN_NAME ORDER BY c.ORDINAL_POSITION SEPARATOR ',' ) INTO v_deploy
            FROM information_schema.COLUMNS AS c
            INNER JOIN `__patch_residui_ordine__` AS o
                ON o.`tabella` = c.TABLE_NAME AND o.`colonna` = c.COLUMN_NAME
            WHERE c.TABLE_SCHEMA = database() AND c.TABLE_NAME = v_tabella;

        SET fine = 0;

        IF v_canone <> v_deploy THEN
            IF EXISTS ( SELECT 1 FROM information_schema.COLUMNS
                        WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND EXTRA LIKE '%GENERATED%' ) THEN
                SET @residui_ordine_note = CONCAT_WS( '\n', @residui_ordine_note, CONCAT( v_tabella, ': ha colonne generate, ordine da sistemare a mano' ) );
            ELSE
                SELECT group_concat(
                        CONCAT( 'MODIFY `', c.COLUMN_NAME, '` ', c.COLUMN_TYPE,
                            IF( c.CHARACTER_SET_NAME IS NULL, '', CONCAT( ' CHARACTER SET ', c.CHARACTER_SET_NAME, ' COLLATE ', c.COLLATION_NAME ) ),
                            IF( c.IS_NULLABLE = 'NO', ' NOT NULL', ' NULL' ),
                            IF( c.COLUMN_DEFAULT IS NULL, '', CONCAT( ' DEFAULT ', c.COLUMN_DEFAULT ) ),
                            IF( c.EXTRA LIKE '%auto_increment%', ' AUTO_INCREMENT', '' ),
                            IF( c.EXTRA LIKE '%on update%', CONCAT( ' ', SUBSTRING( c.EXTRA, LOCATE( 'on update', c.EXTRA ) ) ), '' ),
                            IF( c.COLUMN_COMMENT = '', '', CONCAT( ' COMMENT ', QUOTE( c.COLUMN_COMMENT ) ) ),
                            IF( p.`colonna` IS NULL, ' FIRST', CONCAT( ' AFTER `', p.`colonna`, '`' ) )
                        )
                        ORDER BY o.`posizione` SEPARATOR ', ' )
                    INTO v_clausole
                    FROM `__patch_residui_ordine__` AS o
                    INNER JOIN information_schema.COLUMNS AS c
                        ON c.TABLE_SCHEMA = database() AND c.TABLE_NAME = o.`tabella` AND c.COLUMN_NAME = o.`colonna`
                    LEFT JOIN `__patch_residui_ordine__` AS p
                        ON p.`tabella` = o.`tabella` AND p.`posizione` = (
                            SELECT max( p2.`posizione` ) FROM `__patch_residui_ordine__` AS p2
                            INNER JOIN information_schema.COLUMNS AS c2
                                ON c2.TABLE_SCHEMA = database() AND c2.TABLE_NAME = p2.`tabella` AND c2.COLUMN_NAME = p2.`colonna`
                            WHERE p2.`tabella` = o.`tabella` AND p2.`posizione` < o.`posizione` )
                    WHERE o.`tabella` = v_tabella;
                SET fine = 0;
                BEGIN
                    DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
                        BEGIN
                            GET DIAGNOSTICS CONDITION 1 messaggio = MESSAGE_TEXT;
                            SET errore = 1;
                        END;
                    SET errore = 0;
                    SET foreign_key_checks = 0;
                    SET @residui_sql = CONCAT( 'ALTER TABLE `', v_tabella, '` ', v_clausole );
                    PREPARE riordina FROM @residui_sql;
                    EXECUTE riordina;
                    DEALLOCATE PREPARE riordina;
                    SET foreign_key_checks = @residui_controlli;
                    IF errore = 1 THEN
                        SET @residui_ordine_note = CONCAT_WS( '\n', @residui_ordine_note, LEFT( CONCAT( v_tabella, ': ALTER fallita, ', messaggio ), 500 ) );
                    ELSE
                        SET @residui_ordine_tabelle = @residui_ordine_tabelle + 1;
                    END IF;
                END;
            END IF;
        END IF;

    END LOOP;

    CLOSE lista;

    SET foreign_key_checks = @residui_controlli;

END;

