CREATE OR REPLACE PROCEDURE `__patch_indici_canone__`()
BEGIN
    DECLARE fine INT DEFAULT 0;
    DECLARE errore INT DEFAULT 0;
    DECLARE messaggio TEXT DEFAULT NULL;
    DECLARE v_tabella, v_indice, v_altro CHAR(64) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_tipo CHAR(8) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_colonne, v_presenti VARCHAR(255) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_auto TINYINT DEFAULT 0;
    DECLARE v_unico INT DEFAULT NULL;
    DECLARE v_mancanti INT DEFAULT 0;
    DECLARE v_tipo_id, v_extra_id CHAR(64) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_commento_id VARCHAR(1024) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_esito VARCHAR(255) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_alter TEXT CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_lista_colonne TEXT CHARACTER SET utf8 COLLATE utf8_general_ci;

    DECLARE lista CURSOR FOR
        SELECT `tabella`, `indice`, `tipo`, `colonne`, `auto_increment`
        FROM `__patch_indici_canone__`
        WHERE `esito` IS NULL
        ORDER BY `tabella`, FIELD( `tipo`, 'PRIMARY', 'UNIQUE', 'KEY' ), `indice`;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET fine = 1;

    SET @indici_canone_aggiunti = 0;
    SET @indici_canone_rinominati = 0;
    SET @indici_canone_presenti = 0;
    SET @indici_canone_saltati = 0;
    SET @indici_canone_note = NULL;

    OPEN lista;

    ciclo: LOOP

        FETCH lista INTO v_tabella, v_indice, v_tipo, v_colonne, v_auto;
        IF fine = 1 THEN
            LEAVE ciclo;
        END IF;

        SET v_esito = NULL, v_alter = NULL, v_presenti = NULL, v_unico = NULL, v_altro = NULL;
        SET v_tipo_id = NULL, v_extra_id = NULL, v_commento_id = NULL;
        SET v_lista_colonne = CONCAT( '`', REPLACE( v_colonne, ',', '`,`' ), '`' );

        -- la tabella e le colonne
        IF NOT EXISTS ( SELECT 1 FROM information_schema.TABLES
                WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND TABLE_TYPE = 'BASE TABLE' ) THEN
            SET v_esito = 'tabella mancante';
        ELSE
            SELECT ( LENGTH( v_colonne ) - LENGTH( REPLACE( v_colonne, ',', '' ) ) + 1 ) - COUNT(*) INTO v_mancanti
                FROM information_schema.COLUMNS
                WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND FIND_IN_SET( COLUMN_NAME, v_colonne ) > 0;
            IF v_mancanti > 0 THEN
                SET v_esito = 'colonna mancante';
            END IF;
        END IF;

        -- l'indice col nome del canone, se c'è
        IF v_esito IS NULL THEN
            SELECT GROUP_CONCAT( COLUMN_NAME ORDER BY SEQ_IN_INDEX SEPARATOR ',' ), MIN( NON_UNIQUE ) INTO v_presenti, v_unico
                FROM information_schema.STATISTICS
                WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND INDEX_NAME = v_indice;
        END IF;

        IF v_esito IS NULL AND v_tipo = 'PRIMARY' THEN

            IF v_presenti IS NOT NULL AND v_presenti <> v_colonne THEN
                SET v_esito = CONCAT( 'primaria su ( ', v_presenti, ' ), non toccata' );
            ELSEIF v_colonne <> 'id' THEN
                SET v_esito = 'primaria non su id, non gestita';
            ELSE

                IF v_presenti IS NULL THEN
                    SET @indici_canone_sql = CONCAT( 'SELECT COUNT(*) - COUNT( DISTINCT `id` ), COUNT(*) - COUNT( `id` ) ',
                        'INTO @indici_canone_doppi, @indici_canone_nulli FROM `', v_tabella, '`' );
                    PREPARE conta FROM @indici_canone_sql;
                    EXECUTE conta;
                    DEALLOCATE PREPARE conta;
                    IF @indici_canone_doppi > 0 OR @indici_canone_nulli > 0 THEN
                        SET v_esito = CONCAT( 'primaria non aggiunta: id con ', @indici_canone_doppi, ' doppi e ',
                            @indici_canone_nulli, ' NULL' );
                    ELSE
                        SET v_alter = 'ADD PRIMARY KEY (`id`)';
                    END IF;
                END IF;

                SELECT COLUMN_TYPE, EXTRA, COLUMN_COMMENT INTO v_tipo_id, v_extra_id, v_commento_id
                    FROM information_schema.COLUMNS
                    WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND COLUMN_NAME = 'id';

                IF v_esito IS NULL AND v_auto = 1 AND v_extra_id NOT LIKE '%auto_increment%' AND v_tipo_id NOT LIKE '%int%' THEN
                    -- un id char non può essere AUTO_INCREMENT: la primaria sì, il resto lo deve decidere una patch sui dati
                    SET v_esito = CONCAT( IF( v_alter IS NULL, '', 'primaria aggiunta, ' ), 'AUTO_INCREMENT non aggiunto: id ', v_tipo_id );
                ELSEIF v_esito IS NULL AND v_auto = 1 AND v_extra_id NOT LIKE '%auto_increment%' THEN
                    SET @indici_canone_sql = CONCAT( 'SELECT COUNT(*) INTO @indici_canone_zeri FROM `', v_tabella, '` WHERE `id` = 0' );
                    PREPARE conta FROM @indici_canone_sql;
                    EXECUTE conta;
                    DEALLOCATE PREPARE conta;
                    IF @indici_canone_zeri > 0 THEN
                        SET v_esito = CONCAT( IF( v_alter IS NULL, '', 'primaria aggiunta, ' ),
                            'AUTO_INCREMENT non aggiunto: ', @indici_canone_zeri, ' righe con id 0' );
                    ELSE
                        SET v_alter = CONCAT_WS( ', ', v_alter, CONCAT( 'MODIFY `id` ', v_tipo_id, ' NOT NULL AUTO_INCREMENT',
                            IF( v_commento_id = '', '', CONCAT( ' COMMENT ', QUOTE( v_commento_id ) ) ) ) );
                    END IF;
                END IF;

            END IF;

        ELSEIF v_esito IS NULL THEN

            IF v_presenti IS NOT NULL THEN
                IF v_presenti <> v_colonne OR v_unico <> IF( v_tipo = 'UNIQUE', 0, 1 ) THEN
                    SET v_esito = CONCAT( 'nome usato da un indice ', IF( v_unico = 0, 'unico ', '' ), 'su ( ', v_presenti, ' ), non toccato' );
                END IF;
            ELSE
                -- lo stesso indice con un altro nome, che non sia a sua volta del canone
                SELECT s.INDEX_NAME INTO v_altro
                    FROM information_schema.STATISTICS AS s
                    WHERE s.TABLE_SCHEMA = database() AND s.TABLE_NAME = v_tabella AND s.INDEX_NAME <> 'PRIMARY'
                      AND NOT EXISTS ( SELECT 1 FROM `__patch_indici_canone__` AS c
                            WHERE c.`tabella` = v_tabella AND c.`indice` = s.INDEX_NAME )
                    GROUP BY s.INDEX_NAME
                    HAVING GROUP_CONCAT( s.COLUMN_NAME ORDER BY s.SEQ_IN_INDEX SEPARATOR ',' ) = v_colonne
                       AND MIN( s.NON_UNIQUE ) = IF( v_tipo = 'UNIQUE', 0, 1 )
                    ORDER BY s.INDEX_NAME
                    LIMIT 1;
                SET v_alter = CONCAT( IF( v_altro IS NULL, '', CONCAT( 'DROP INDEX `', v_altro, '`, ' ) ),
                    'ADD ', IF( v_tipo = 'UNIQUE', 'UNIQUE ', '' ), 'KEY `', v_indice, '` (', v_lista_colonne, ')' );
            END IF;

        END IF;

        -- fine si alza anche quando una delle SELECT qui sopra non trova niente
        SET fine = 0;

        IF v_alter IS NOT NULL THEN
            BEGIN
                DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
                    BEGIN
                        -- conta il primo errore: EXECUTE e DEALLOCATE dopo una PREPARE fallita ne aggiungono altri
                        IF errore = 0 THEN
                            GET DIAGNOSTICS CONDITION 1 messaggio = MESSAGE_TEXT;
                        END IF;
                        SET errore = 1;
                    END;
                SET errore = 0;
                SET @indici_canone_sql = CONCAT( 'ALTER TABLE `', v_tabella, '` ', v_alter );
                PREPARE cambia FROM @indici_canone_sql;
                EXECUTE cambia;
                DEALLOCATE PREPARE cambia;
                IF errore = 1 THEN
                    SET v_esito = LEFT( CONCAT( 'errore: ', messaggio ), 255 );
                ELSEIF v_altro IS NOT NULL THEN
                    SET v_esito = LEFT( CONCAT( 'rinominato da ', v_altro ), 255 );
                ELSE
                    SET v_esito = IFNULL( v_esito, 'aggiunto' );
                END IF;
            END;
        END IF;

        SET v_esito = IFNULL( v_esito, 'presente' );

        UPDATE `__patch_indici_canone__` SET `esito` = v_esito
            WHERE `tabella` = v_tabella AND `indice` = v_indice;

        IF v_esito = 'aggiunto' THEN
            SET @indici_canone_aggiunti = @indici_canone_aggiunti + 1;
        ELSEIF v_esito LIKE 'rinominato da %' THEN
            SET @indici_canone_rinominati = @indici_canone_rinominati + 1;
        ELSEIF v_esito = 'presente' THEN
            SET @indici_canone_presenti = @indici_canone_presenti + 1;
        ELSE
            SET @indici_canone_saltati = @indici_canone_saltati + 1;
            IF v_esito NOT IN ( 'tabella mancante', 'colonna mancante' ) THEN
                SET @indici_canone_note = CONCAT_WS( '\n', @indici_canone_note, CONCAT( v_tabella, '.', v_indice, ': ', v_esito ) );
            END IF;
        END IF;

    END LOOP;

    CLOSE lista;

END;

