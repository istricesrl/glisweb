-- Contesto: i file di base dichiarano per ogni tabella la chiave primaria su id, l'AUTO_INCREMENT e gli indici
-- ( _030000999999.indexes.sql, e dentro la CREATE per ACL e viste statiche ), ma un deploy li riceve solo
-- all'installazione: le tabelle aggiunte dopo da una patch che non li creava, o ricreate a mano, ne restano senza.
-- Misurato il 02/10/2026 con canone-vivo.py: sul DB di glisdev 50 tabelle non hanno nessun indice, nemmeno la
-- primaria ( fra queste colli e comuni, che ha 18.115 righe ), e mancano 962 indici; sul master di glisweb 8
-- tabelle senza primaria, 16 id senza AUTO_INCREMENT, 337 indici mancanti. Una tabella senza primaria non regge il
-- REPLACE delle statiche e lascia che due righe abbiano lo stesso id; un indice mancante su un id_* rende lenta
-- ogni JOIN della vista.
--
-- COSA FA. Riprende la lista di TUTTI gli indici dei file di base ( 2.409: 253 primarie, 258 unici, 1.898 semplici )
-- e per ognuno, sulle tabelle vere del database:
--
-- -# la primaria: se manca la aggiunge su id, ma solo se id non ha valori NULL né doppi; se il canone vuole
--    l'AUTO_INCREMENT e id non ce l'ha lo aggiunge, tenendo tipo e commento, ma solo se id è intero ( un id char
--    resta senza, e lo scrive nella nota ) e nessuna riga ha id 0 ( l'AUTO_INCREMENT la rinumererebbe e romperebbe
--    chi la cita ); una primaria su altre colonne non si tocca;
-- -# un indice che c'è già col suo nome e le sue colonne si conta come "presente";
-- -# un indice che c'è con le stesse colonne e la stessa unicità ma un altro nome ( tipicamente quello che InnoDB
--    crea da sé per una chiave esterna, p.es. anagrafica_categorie_ibfk_01 ) prende il nome del canone, con una
--    DROP e una ADD nella stessa ALTER; non se l'altro nome è a sua volta un indice del canone;
-- -# un indice che manca si aggiunge; un unico che trova valori doppi non si aggiunge e lo scrive nella nota;
-- -# un indice che c'è col nome del canone ma su altre colonne non si tocca, e lo scrive nella nota.
--
-- Le tabelle che mancano e gli indici su colonne che mancano si saltano: li porterà la patch che crea la tabella o
-- la colonna. Nessun indice in più viene tolto.
--
-- Va applicata PRIMA di _202610021500.tipi.canonici.sql: le conversioni di tipo trovano così id già chiave primaria,
-- e _202610021700.chiavi.esterne.canone.sql trova gli indici col nome del canone e non ne crea di suoi.
-- Aggiungere una primaria ricopia la tabella; gli altri indici no.
--
-- L'esito è in @indici_canone_*, che il blocco dopo la CALL restituisce.
--
-- IDEMPOTENTE: una seconda esecuzione trova tutto "presente".

