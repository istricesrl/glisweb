-- _202610021700.chiavi.esterne.canone.sql aggiunge i vincoli che mancano e lascia stare una colonna che un vincolo ce
-- l'ha gia', anche col nome vecchio ( ibfk_1, ibfk_2... dei dump di MySQL ) o con regole diverse ( spesso RESTRICT, il
