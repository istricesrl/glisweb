CREATE OR REPLACE PROCEDURE `__patch_residui_chiavi__`()
BEGIN

    DECLARE fine INT DEFAULT 0;
    DECLARE errore INT DEFAULT 0;
    DECLARE messaggio TEXT DEFAULT NULL;
    DECLARE v_tabella, v_vincolo, v_colonna, v_riferimento CHAR(64) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_cancellazione, v_aggiornamento CHAR(16) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_tipo_figlia, v_tipo_padre, v_nullabile CHAR(64) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_esito VARCHAR(500) CHARACTER SET utf8 COLLATE utf8_general_ci;
    DECLARE v_quanti, v_giusti INT;
    DECLARE v_togli, v_rimetti, v_indice TEXT CHARACTER SET utf8 COLLATE utf8_general_ci;

    DECLARE lista CURSOR FOR
        SELECT `tabella`, `vincolo`, `colonna`, `riferimento`, `cancellazione`, `aggiornamento`
        FROM `__patch_residui_chiavi__`
        WHERE `esito` IS NULL
        ORDER BY `tabella`, `vincolo`;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET fine = 1;

    SET SESSION group_concat_max_len = 1048576;
    SET @residui_controlli = @@foreign_key_checks;
    SET @residui_chiavi_corrette = 0;
    SET @residui_chiavi_aggiunte = 0;
    SET @residui_chiavi_note = NULL;

    OPEN lista;

    ciclo: LOOP

        FETCH lista INTO v_tabella, v_vincolo, v_colonna, v_riferimento, v_cancellazione, v_aggiornamento;
        IF fine = 1 THEN
            LEAVE ciclo;
        END IF;

        SET v_esito = NULL, v_tipo_figlia = NULL, v_tipo_padre = NULL, v_nullabile = NULL, v_togli = NULL, v_rimetti = NULL, v_indice = NULL;

        SELECT COLUMN_TYPE, IS_NULLABLE INTO v_tipo_figlia, v_nullabile
            FROM information_schema.COLUMNS
            WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND COLUMN_NAME = v_colonna
            LIMIT 1;
        SELECT COLUMN_TYPE INTO v_tipo_padre
            FROM information_schema.COLUMNS
            WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_riferimento AND COLUMN_NAME = 'id'
            LIMIT 1;
        SET fine = 0;

        -- i vincoli che la colonna ha adesso, e quanti sono esattamente quello del canone
        SELECT count(*),
               sum( BINARY k.CONSTRAINT_NAME = BINARY v_vincolo AND k.REFERENCED_TABLE_NAME = v_riferimento
                    AND k.REFERENCED_COLUMN_NAME = 'id' AND r.DELETE_RULE = v_cancellazione AND r.UPDATE_RULE = v_aggiornamento ),
               group_concat( CONCAT( 'DROP FOREIGN KEY `', k.CONSTRAINT_NAME, '`' ) SEPARATOR ', ' ),
               group_concat( CONCAT( 'ADD CONSTRAINT `', k.CONSTRAINT_NAME, '` FOREIGN KEY (`', v_colonna, '`) REFERENCES `',
                   k.REFERENCED_TABLE_NAME, '` (`', k.REFERENCED_COLUMN_NAME, '`) ON DELETE ', r.DELETE_RULE, ' ON UPDATE ', r.UPDATE_RULE ) SEPARATOR ', ' )
            INTO v_quanti, v_giusti, v_togli, v_rimetti
            FROM information_schema.KEY_COLUMN_USAGE AS k
            INNER JOIN information_schema.REFERENTIAL_CONSTRAINTS AS r
                ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND r.TABLE_NAME = k.TABLE_NAME
            WHERE k.TABLE_SCHEMA = database() AND k.TABLE_NAME = v_tabella AND k.COLUMN_NAME = v_colonna
              AND k.REFERENCED_TABLE_NAME IS NOT NULL;
        SET fine = 0;

        IF v_quanti = 1 AND v_giusti = 1 THEN
            SET v_esito = 'presente';
        ELSEIF v_tipo_figlia IS NULL THEN
            SET v_esito = CONCAT( 'non esiste ', v_tabella, '.', v_colonna );
        ELSEIF v_tipo_padre IS NULL THEN
            SET v_esito = CONCAT( 'non esiste ', v_riferimento, '.id' );
        ELSEIF v_tipo_figlia <> v_tipo_padre THEN
            SET v_esito = CONCAT( 'tipi diversi, ', v_tabella, '.', v_colonna, ' ', v_tipo_figlia, ' e ', v_riferimento, '.id ', v_tipo_padre );
        ELSEIF v_cancellazione = 'SET NULL' AND v_nullabile = 'NO' THEN
            SET v_esito = CONCAT( v_tabella, '.', v_colonna, ' e'' NOT NULL e il vincolo e'' ON DELETE SET NULL' );
        ELSEIF EXISTS (
            SELECT 1 FROM information_schema.TABLE_CONSTRAINTS AS tc
            WHERE tc.CONSTRAINT_SCHEMA = database() AND BINARY tc.CONSTRAINT_NAME = BINARY v_vincolo
              AND NOT EXISTS ( SELECT 1 FROM information_schema.KEY_COLUMN_USAGE AS k2
                               WHERE k2.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA AND k2.CONSTRAINT_NAME = tc.CONSTRAINT_NAME
                                 AND k2.TABLE_NAME = v_tabella AND k2.COLUMN_NAME = v_colonna )
        ) THEN
            SET v_esito = 'il nome e'' gia'' usato da un vincolo su un''altra colonna';
        END IF;

        -- righe orfane
        IF v_esito IS NULL THEN
            BEGIN
                DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
                    BEGIN
                        GET DIAGNOSTICS CONDITION 1 messaggio = MESSAGE_TEXT;
                        SET errore = 1;
                    END;
                SET errore = 0, @residui_orfani = NULL;
                SET @residui_sql = CONCAT(
                    'SELECT count(*) INTO @residui_orfani FROM `', v_tabella, '` AS figlie ',
                    'LEFT JOIN `', v_riferimento, '` AS padri ON padri.id = figlie.`', v_colonna, '` ',
                    'WHERE figlie.`', v_colonna, '` IS NOT NULL AND padri.id IS NULL' );
                PREPARE controllo FROM @residui_sql;
                EXECUTE controllo;
                DEALLOCATE PREPARE controllo;
                IF errore = 1 THEN
                    SET v_esito = LEFT( CONCAT( 'controllo delle righe orfane fallito: ', messaggio ), 500 );
                ELSEIF @residui_orfani > 0 THEN
                    SET v_esito = CONCAT( @residui_orfani, ' righe di ', v_tabella, ' con un ', v_colonna, ' che non esiste in ', v_riferimento );
                END IF;
            END;
        END IF;

        IF v_esito IS NULL THEN
            IF NOT EXISTS (
                SELECT 1 FROM information_schema.STATISTICS
                WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND COLUMN_NAME = v_colonna AND SEQ_IN_INDEX = 1
            ) AND NOT EXISTS (
                SELECT 1 FROM information_schema.STATISTICS
                WHERE TABLE_SCHEMA = database() AND TABLE_NAME = v_tabella AND INDEX_NAME = v_colonna
            ) THEN
                SET v_indice = CONCAT( 'ADD KEY `', v_colonna, '` (`', v_colonna, '`), ' );
            END IF;
            BEGIN
                DECLARE CONTINUE HANDLER FOR SQLEXCEPTION
                    BEGIN
                        GET DIAGNOSTICS CONDITION 1 messaggio = MESSAGE_TEXT;
                        SET errore = 1;
                    END;
                SET errore = 0;
                SET foreign_key_checks = 0;
                IF v_togli IS NOT NULL THEN
                    SET @residui_sql = CONCAT( 'ALTER TABLE `', v_tabella, '` ', v_togli );
                    PREPARE togli FROM @residui_sql;
                    EXECUTE togli;
                    DEALLOCATE PREPARE togli;
                END IF;
                IF errore = 1 THEN
                    SET v_esito = LEFT( CONCAT( 'non si riesce a togliere i vincoli di prima: ', messaggio ), 500 );
                ELSE
                    SET @residui_sql = CONCAT(
                        'ALTER TABLE `', v_tabella, '` ', IFNULL( v_indice, '' ),
                        'ADD CONSTRAINT `', v_vincolo, '` FOREIGN KEY (`', v_colonna, '`) REFERENCES `', v_riferimento, '` (`id`) ',
                        'ON DELETE ', v_cancellazione, ' ON UPDATE ', v_aggiornamento );
                    PREPARE metti FROM @residui_sql;
                    EXECUTE metti;
                    DEALLOCATE PREPARE metti;
                    IF errore = 1 THEN
                        SET v_esito = LEFT( CONCAT( 'il vincolo del canone non entra: ', messaggio ), 500 );
                        IF v_rimetti IS NOT NULL THEN
                            SET errore = 0;
                            SET @residui_sql = CONCAT( 'ALTER TABLE `', v_tabella, '` ', v_rimetti );
                            PREPARE metti FROM @residui_sql;
                            EXECUTE metti;
                            DEALLOCATE PREPARE metti;
                            SET v_esito = LEFT( CONCAT( v_esito, IF( errore = 1, ' -- E NON SI RIESCE A RIMETTERE QUELLI DI PRIMA: ', ' -- rimessi quelli di prima' ), IF( errore = 1, v_rimetti, '' ) ), 500 );
                        END IF;
                    ELSEIF v_togli IS NULL THEN
                        SET v_esito = 'aggiunto', @residui_chiavi_aggiunte = @residui_chiavi_aggiunte + 1;
                    ELSE
                        SET v_esito = 'corretto', @residui_chiavi_corrette = @residui_chiavi_corrette + 1;
                    END IF;
                END IF;
                SET foreign_key_checks = @residui_controlli;
            END;
        END IF;

        UPDATE `__patch_residui_chiavi__` SET `esito` = v_esito WHERE `tabella` = v_tabella AND `vincolo` = v_vincolo;

        IF v_esito NOT IN ( 'presente', 'aggiunto', 'corretto' ) THEN
            SET @residui_chiavi_note = CONCAT_WS( '\n', @residui_chiavi_note, CONCAT( v_vincolo, ': ', v_esito ) );
        END IF;

    END LOOP;

    CLOSE lista;

    SET foreign_key_checks = @residui_controlli;

END;

