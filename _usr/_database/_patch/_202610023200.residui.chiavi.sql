-- stessa colonna. Questa patch riprende la lista di tutti i vincoli di _060000999999.constraints.sql e, per ogni
-- colonna:
--
-- -# se ha esattamente il vincolo del canone ( nome, tabella riferita, ON DELETE e ON UPDATE ) non fa niente;
-- -# altrimenti, se tipi, NULL e righe orfane lo permettono, toglie i vincoli che la colonna ha e mette quello del
--    canone ( con l'indice, se la colonna non ne ha uno ); se il nuovo non entra rimette quelli di prima, cosi' la
--    colonna non resta mai senza. Due passi, perche' MariaDB non accetta di togliere e rimettere un vincolo con lo
--    stesso nome nella stessa ALTER ( errore 1826, provato il 02/10/2026 su 10.3.39 ).
--
-- Porta anche la decisione di Fabio del 02/10/2026 su metadati: le chiavi verso gli oggetti descritti passano da
-- SET NULL a CASCADE. I metadati gia' senza oggetto ( su polmasi 40mila, su gimbe 74 ) restano: il vincolo non li
-- vede, e cancellarli e' un'altra decisione.
--
-- I vincoli che il canone non ha, su colonne che il canone non vincola, non si toccano. Va dopo
-- _202610023000.residui.colonne.sql, che porta i tipi al canone. IDEMPOTENTE.

